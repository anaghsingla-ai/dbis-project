import React, { useState, useEffect } from 'react';
import api from '../../api/client';
import { useToast } from '../../context/ToastContext';
import { ScrollText, RefreshCw, ArrowRight, TrendingUp } from 'lucide-react';
import Button from '../../components/common/Button';
import Badge from '../../components/common/Badge';
import { EmptyState } from '../../components/common/Input';

export default function CoordinatorAudit() {
  const [logs, setLogs] = useState([]);
  const [loading, setLoading] = useState(true);
  const { showToast } = useToast();

  const loadLogs = async () => {
    setLoading(true);
    try {
      const res = await api.get('/coordinator/audit-history');
      if (res.success) setLogs(res.logs);
    } catch (err) {
      showToast('Error loading audit history: ' + err.message, 'error');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadLogs();
  }, []);

  return (
    <div className="space-y-6 animate-fadeInUp">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div>
          <h1 className="text-2xl font-black text-white tracking-tight">Academic Audit Trail</h1>
          <p className="text-sm text-slate-400 mt-1">
            Automatic audit records for CGPA and backlog modifications in your department.
          </p>
        </div>
        <Button
          size="sm"
          variant="secondary"
          onClick={loadLogs}
          isLoading={loading}
          leftIcon={<RefreshCw className="w-3.5 h-3.5" />}
        >
          Refresh
        </Button>
      </div>

      {/* Stats */}
      <div className="grid grid-cols-2 sm:grid-cols-3 gap-4">
        {[
          { label: 'Total Audit Records', value: logs.length, color: 'text-cyan-400' },
          { label: 'CGPA Updates', value: logs.filter(l => l.field_changed === 'cgpa').length, color: 'text-emerald-400' },
          { label: 'Backlog Updates', value: logs.filter(l => l.field_changed === 'backlog_count').length, color: 'text-amber-400' },
        ].map(s => (
          <div key={s.label} className="bg-slate-800/50 border border-slate-700/50 rounded-xl p-4">
            <div className={`text-2xl font-black ${s.color}`}>{s.value}</div>
            <div className="text-xs text-slate-400 mt-1">{s.label}</div>
          </div>
        ))}
      </div>

      {/* Audit Log Table */}
      <div className="bg-slate-900/60 border border-slate-700/50 rounded-2xl overflow-hidden">
        <div className="px-5 py-4 border-b border-slate-700/50 flex items-center gap-3">
          <ScrollText className="w-4 h-4 text-cyan-400" />
          <span className="text-sm font-semibold text-slate-200">Audit Events</span>
          <span className="ml-auto text-xs text-slate-500">Auto-generated by database triggers on record changes</span>
        </div>

        {loading ? (
          <div className="py-16 text-center text-slate-400 text-sm">Loading audit logs...</div>
        ) : logs.length === 0 ? (
          <EmptyState
            icon={<ScrollText className="w-8 h-8" />}
            title="No audit records yet"
            description="Audit records are created automatically whenever student academic records are updated."
          />
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs border-collapse">
              <thead>
                <tr className="border-b border-slate-700/50 text-slate-400 font-semibold uppercase tracking-wider">
                  <th className="py-3 px-4">Log ID</th>
                  <th className="py-3 px-4">Student</th>
                  <th className="py-3 px-4">Field Changed</th>
                  <th className="py-3 px-4">Before</th>
                  <th className="py-3 px-4">After</th>
                  <th className="py-3 px-4">Source</th>
                  <th className="py-3 px-4">Timestamp</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-700/30">
                {logs.map((log) => (
                  <tr key={log.log_id} className="hover:bg-slate-800/40 transition-colors">
                    <td className="py-3 px-4 font-mono text-slate-500">#{log.log_id}</td>
                    <td className="py-3 px-4">
                      <div className="font-medium text-slate-200">{log.student_name || `Roll #${log.record_id}`}</div>
                      <div className="text-[10px] text-slate-500 font-mono">{log.enrollment_no}</div>
                    </td>
                    <td className="py-3 px-4">
                      <span className="font-mono font-semibold text-cyan-400 bg-cyan-900/30 border border-cyan-500/30 px-2 py-0.5 rounded">
                        {log.field_changed}
                      </span>
                    </td>
                    <td className="py-3 px-4">
                      <span className="text-rose-400 bg-rose-900/30 border border-rose-500/30 px-2 py-0.5 rounded font-mono font-medium">
                        {log.old_value ?? 'NULL'}
                      </span>
                    </td>
                    <td className="py-3 px-4">
                      <div className="flex items-center gap-1.5 font-mono">
                        <ArrowRight className="w-3 h-3 text-slate-500" />
                        <span className="text-emerald-400 bg-emerald-900/30 border border-emerald-500/30 px-2 py-0.5 rounded font-bold">
                          {log.new_value ?? 'NULL'}
                        </span>
                      </div>
                    </td>
                    <td className="py-3 px-4">
                      <Badge variant="amber" size="sm">Auto-Trigger</Badge>
                    </td>
                    <td className="py-3 px-4 text-slate-400 font-mono">
                      {log.changed_at ? new Date(log.changed_at).toLocaleString() : '—'}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
}
